// Short Object Properties (বা Object Property Shorthand) হলো JavaScript (ES6)-এর একটি সহজ ফিচার।

// যখন কোনো অবজেক্টের key (প্রপার্টির নাম) এবং value (যে ভ্যারিয়েবল থেকে ডেটা আসছে) দুটি একই নামের হয়, তখন একই নাম বারবার না লিখে সংক্ষেপে একবার লিখলেই কাজ হয়ে যায়।

// পার্থক্য (উদাহরণ সহ)
// ১. সাধারণ নিয়ম (Shorthand ছাড়া)

let name = "Rahim";
let age = 25;

// আগে যেভাবে লিখতে হতো:
let user = {
  name: name,
  age: age,
};

// ২. Short Object Properties (Shorthand সহ)

let name = "Rahim";
let age = 25;

// এখন যেভাবে লেখা যায়:
let user = {
  name,
  age,
};

