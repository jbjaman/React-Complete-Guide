const nums = [10, 20, 30, 40];

console.log(nums.splice(1, 2)); // [ 20, 30 ]
console.log(nums); // [ 10, 40 ]

// splice(startIndex, deleteCount): মূল অ্যারেকে সরাসরি বদলে দেয় (Mutable) এবং কেটে ফেলা অংশটি আলাদা অ্যারে হিসেবে রিটার্ন করে।

// JavaScript-এ splice() মেথডটি মূল অ্যারেকে সরাসরি পরিবর্তন করে (Mutable) এবং অ্যারে থেকে নির্দিষ্ট উপাদান কেটে বের করে নিয়ে আসে।
// splice() কেটে নেওয়া উপাদানগুলো দিয়ে একটি নতুন অ্যারে রিটার্ন করে, তাই প্রথম লগে কেটে নেওয়া উপাদান [20, 30] আউটপুট এসেছে।
// যেহেতু splice() মূল অ্যারেকে সরাসরি বদলে দেয়, তাই 20 এবং 30 সরে যাওয়ার পর মূল nums অ্যারেতে এখন বাকি থাকে শুধু প্রথম ও শেষ উপাদান: [10, 40]।

// splice(1, 2): মূল অ্যারে থেকে কেটে বের করে নেয়, তাই মূল অ্যারে বদলে যায়।
// slice(1, 2): কপি করে নিয়ে আসে, মূল অ্যারে অক্ষত থাকে।
