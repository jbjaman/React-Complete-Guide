const numbers = [10, 1, 3];

const sort1 = numbers.sort();
// JavaScript-এ numbers.sort() কোনো প্রোপার কম্পারেটর ফাংশন ছাড়া ব্যবহার করলে সে সংখ্যাগুলোকে প্রথমে String (লেখা)-এ রূপান্তর করে এবং অ্যালফাবেটিকাল বা লেক্সিকোগ্রাফিকাল (Lexicographical) অর্ডারে সাজায়।
// ডিকশনারি বা বর্ণমালার নিয়মে "1" সবার আগে আসে, তারপর "10" (কারণ এটি ১ দিয়ে শুরু), এবং শেষে "3" আসে।
console.log(sort1); // [1,10,3]

const sort2 = numbers.sort((a, b) => {
  return a - b;
});
// sort2-তে আপনি একটি নির্দিষ্ট নিয়ম (a, b) => a - b বলে দিয়েছেন। এটি সঠিক গাণিতিক নিয়মে ছোট থেকে বড় (Ascending Order) হিসেবে সাজায়।
console.log(sort2); // [1,3,10]

const numbers2 = [10, 1, 3];

// তাহলে sort21 কেন [1, 3, 10] দিল?

// কারণ sort() মেথডটি Mutable (পরিবর্তনযোগ্য)। এটি আসল বা মূল অ্যারেটিকে সরাসরি বদলে দেয়।
const sort21 = numbers2.sort();
// এটি মূল numbers অ্যারেটিকে বদলে বানিয়ে দিয়েছিল: [1, 10, 3]।
const sort22 = numbers2.sort((a, b) => {
  return a - b;
});
// এটি আবার ওই একই numbers অ্যারেটিকেই দ্বিতীয়বার ওভাররাইট করে সঠিক গাণিতিক অর্ডারে সাজিয়ে বানিয়ে দিল: [1, 3, 10]।
console.log(sort21); // [1,3,10]
console.log(sort22); // [1,3,10]
