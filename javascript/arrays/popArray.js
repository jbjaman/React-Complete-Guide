const numbers = [10, 20, 30];

console.log(numbers.pop()); // 30
console.log(numbers); // [10, 20]

// JavaScript-এ pop() মেথডটি অ্যারের একদম শেষের উপাদানটিকে সরিয়ে ফেলে এবং সরিয়ে নেওয়া উপাদানটিকেই রিটার্ন করে।
// যেহেতু pop() মেথডটি মূল অ্যারেকে সরাসরি বদলে দেয় (Mutable), তাই 30 সরে যাওয়ার পর অ্যারেতে এখন বাকি আছে শুধু [10, 20]
// numbers.pop(): এটি numbers অ্যারের শেষ উপাদান 30-কে কেটে বের করে নিয়ে আসে। তাই console.log(numbers.pop()) করলে স্ক্রিনে কেটে বের করে নেওয়া মান 30 দেখা যায়।

/**
 * push(): নতুন মান যুক্ত করে এবং অ্যারের নতুন দৈর্ঘ্য (Length) রিটার্ন করে।
 * pop(): শেষ মানটি সরিয়ে দেয় এবং যে মানটি সরানো হলো সেটিই রিটার্ন করে।
 */
