const scores = [45, 60, 75, 90];

const result = scores.every((score) => score >= 62);

console.log(result); // false
console.log(scores); // [45, 60, 75, 90];

// JavaScript-এ every() মেথডটি চেক করে অ্যারের প্রতিটি (সবগুলো) উপাদান শর্ত পূরণ করছে কি না।

// some()-এর মতো এটিও একটি Boolean মেথড—অর্থাৎ এটি শুধুমাত্র true অথবা false রিটার্ন করে।

// every() মেথডের নিয়ম হলো সবগুলোকে শর্ত পূরণ করতে হবে। যেহেতু একটা ভুল পাওয়া গেছে, সে আর বাকিগুলো চেকই করে না—সরাসরি false রিটার্ন করে দেয়।

console.log([].every((x) => x > 0)); // true

// every() যেভাবে কাজ করে: সে অ্যারের ভেতর থেকে একটি উপাদান ধরে এবং শর্ত চেক করে। যদি কোথাও শর্ত ভাঙার মতো কোনো ভুল উপাদান (Counter-example) পায়, তবেই সে false ফেরত দেয়। কিন্তু খালি অ্যারেতে এমন কোনো উপাদানই নেই যা শর্তটিকে ভুল/মিথ্যা প্রমাণ করতে পারে।
// যেহেতু every() ভুল প্রমাণ করার মতো কোনো উপাদান খুঁজে পায়নি, তাই লজিক অনুযায়ী সেটিকে ধরে নেওয়া হয় true।
