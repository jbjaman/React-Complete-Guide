const ages = [12, 18, 25, 15, 30];

const adults = ages.filter((age) => age >= 18);

console.log(adults); // [18,25,30]
console.log(ages); // [12, 18, 25, 15, 30];

// filter() মেথডটি অ্যারের প্রতিটি উপাদানের জন্য একটি Callback ফাংশন চালায় এবং একটি শর্ত (Condition) চেক করে।

// আপনার শর্ত: age >= 18 (বয়স ১৮ বা ১৮-এর বেশি হতে হবে)।

// Callback ফাংশনটির কাজ: প্রতিটি সংখ্যার ক্ষেত্রে সে true নাকি false তা যাচাই করে:

// filter() কখনো মূল অ্যারেকে পরিবর্তন করে না। এটি ছেঁকে বের করা মানগুলো দিয়ে একদম একটি নতুন অ্যারে তৈরি করে উপহার দেয়।
