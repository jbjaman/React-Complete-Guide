const numbers = [10, 20, 30];

console.log(numbers.shift()); // 10
console.log(numbers); // [20, 30]

// JavaScript-এ shift() মেথডটি অ্যারের সবচেয়ে প্রথম উপাদানটিকে বের (Remove) করে দেয় এবং যে উপাদানটিকে বের করা হলো, সেটিকেই রিটার্ন করে।
// shift() মেথডটি numbers অ্যারের একদম প্রথম উপাদান 10-কে কেটে বের করে নিয়ে আসে।
// যেহেতু এটি অপসারিত উপাদানটিকেই রিটার্ন করে, তাই প্রথম লগে 10 আউটপুট এসেছে।
// shift() মেথডটি মূল অ্যারেকে বদলে দেয় (Mutable)।
// 10 বের হয়ে যাওয়ার পর অ্যারেতে এখন বাকি উপাদান থাকে [20, 30], তাই দ্বিতীয় লগে আপডেট হওয়া অ্যারে [20, 30] দেখিয়েছে।
