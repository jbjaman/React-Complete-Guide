const numbers = [10, 20, 30];

console.log(numbers.unshift(40)); // 4
console.log(numbers); // [40, 10, 20, 30]

// JavaScript-এ unshift() মেথডটি অ্যারের শুরুতে (প্রথম দিকে) নতুন মান যুক্ত করার কাজ করে।
// unshift() মেথডটি push()-এর মতোই অ্যারের নতুন মোট দৈর্ঘ্য (Length) রিটার্ন করে।
// unshift() একটি Mutable মেথড, যা মূল অ্যারেকে সরাসরি পরিবর্তন করে দেয়।
// তাই numbers প্রিন্ট করায় নতুন করে সাজানো অ্যারে [40, 10, 20, 30] আউটপুট দিয়েছে।
