const scores = [45, 60, 75, 90];

const result = scores.some((score) => score >= 62);

console.log(result); // true
console.log(scores); // [45, 60, 75, 90];

// JavaScript-এ some() মেথডটি চেক করে অ্যারের কমপক্ষে যেকোনো একটি উপাদান শর্ত পূরণ করে কি না।

// এটি একটি Boolean মেথড—অর্থাৎ এটি কোনো অ্যারে বা উপাদান ফেরত দেয় না, শুধুমাত্র true অথবা false রিটার্ন করে।

// আপনার দেওয়া শর্ত: score >= 62 (মান ৬২ বা তার বড় হতে হবে)।

// some() মেথডটি অ্যারের উপাদানগুলো চেক করা শুরু করে:

// যেহেতু সে অন্তত একটি উপাদান (75) পেয়ে গেছে যা ৬২-এর চেয়ে বড়, সে সাথে সাথে খোঁজা বন্ধ করে দেয় এবং true রিটার্ন করে।

// some(): অ্যারের যেকোনো একটি মান শর্ত পূরণ করলেই true দেবে।

// every(): অ্যারের সবগুলো মানকে শর্ত পূরণ করতে হবে, তবেই true দেবে (অন্যথায় false)।

console.log([].some((x) => x > 0)); // false

// এখানে অ্যারেটি একদম খালি ([]) যেহেতু ভেতরে কোনো উপাদানই নেই, তাই শর্ত পূরণ করার মতো কোনো মান পাওয়ার কোনো প্রশ্নই ওঠে না। তাই কোনো উপাদান না পাওয়ায় এটি false দেয়।
