const nums = [10, 20, 30, 40, 50, 60];

console.log(nums.slice(1, 3)); // [20, 30]
console.log(nums); // [10, 20, 30, 40, 50, 60]

// JavaScript-এ slice() মেথডটির কাজ হলো অ্যারের নির্দিষ্ট অংশ কেটে নিয়ে একটি নতুন অ্যারে (New Array) তৈরি করা। এটি মূল অ্যারেকে কখনো পরিবর্তন করে না, অর্থাৎ slice() হলো একটি Immutable মেথড।
// slice(1, 3)-এর অর্থ হলো Index 1 থেকে শুরু করে Index 3-এর আগে পর্যন্ত উপাদান নেওয়া (শেষের Index 3 বাদ যাবে)।
// তাই শুধুমাত্র মান 20, 30 নেওয়া হয়েছে। যেহেতু slice() সবসময় একটি নতুন অ্যারে রিটার্ন করে, তাই আউটপুট এসেছে [20, 30]।
// যেহেতু slice() মূল অ্যারেকে স্পর্শ করে না (Immutable), তাই মূল nums অ্যারেটি আগের মতোই [10, 20, 30, 40] রয়ে গেছে।

// slice(startIndex, endIndex): মূল অ্যারে পরিবর্তন করে না (Immutable)। শুধু নির্দিষ্ট অংশ কেটে একটি নতুন অ্যারে বানিয়ে দেয়।
